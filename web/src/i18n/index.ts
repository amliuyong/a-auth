function initialLang(): string {
  const url = new URLSearchParams(window.location.search).get('ui_locales');
  if (url?.startsWith('zh')) return 'zh';
  if (url?.startsWith('en')) return 'en';
  const saved = localStorage.getItem('agent-auth-lang');
  if (saved === 'zh' || saved === 'en') return saved;
  return navigator.language.startsWith('zh') ? 'zh' : 'en';
}

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLang(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

export function setLang(lang: 'zh' | 'en') {
  localStorage.setItem('agent-auth-lang', lang);
  void i18n.changeLanguage(lang);
}

export default i18n;
