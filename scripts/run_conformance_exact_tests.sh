executed_exact_tests=0

run_exact() {
  local test_target="$1"
  local selector="$2"
  local listed
  listed="$(
    cargo test -p agent-auth-http --features aws --locked \
      --test "$test_target" "$selector" -- --exact --list
  )"
  if ! grep -Fqx "$selector: test" <<<"$listed"; then
    printf 'exact conformance selector is not registered: %s/%s\n' \
      "$test_target" "$selector" >&2
    return 1
  fi
  cargo test -p agent-auth-http --features aws --locked \
    --test "$test_target" "$selector" -- --exact --test-threads=1
  executed_exact_tests=$((executed_exact_tests + 1))
}

run_lib_exact() {
  local package="$1"
  local cargo_selector="$2"
  local listed
  local feature_args=()
  if [[ "$package" == "agent-auth-http" ]]; then
    if [[ "$cargo_selector" == "cimd::tests::http_transport_pins_tls_and_enforces_redirect_size_and_timeout" ]]; then
      feature_args=(--features transport-test)
    elif [[ "$cargo_selector" == mtls::tests::lambda_request_context_is_the_only_* ]]; then
      feature_args=(--features aws,lambda)
    else
      feature_args=(--features aws)
    fi
  fi
  listed="$(
    cargo test -p "$package" "${feature_args[@]}" --lib --locked \
      "$cargo_selector" -- --exact --list
  )"
  if ! grep -Fqx "$cargo_selector: test" <<<"$listed"; then
    printf 'exact conformance library selector is not registered: %s/%s\n' \
      "$package" "$cargo_selector" >&2
    return 1
  fi
  cargo test -p "$package" "${feature_args[@]}" --lib --locked \
    "$cargo_selector" -- --exact --test-threads=1
  executed_exact_tests=$((executed_exact_tests + 1))
}

